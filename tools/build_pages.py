def numbered(items, n=None):
    n = n or len(items)
    cells = "".join(
        f'<div><span class="vx-mono">{i:02d} &middot; {lab}</span><h3>{h}</h3><p>{p}</p></div>'
        for i, (lab, h, p) in enumerate(items, 1)
    )
    return f'<div class="vx-numbered" style="--n:{n}">{cells}</div>'


def cols(items, n=None):
    n = n or len(items)
    cells = "".join(f'<div class="vx-col {tone}">{inner}</div>' for tone, inner in items)
    return f'<div class="vx-cols" style="--n:{n}">{cells}</div>'


