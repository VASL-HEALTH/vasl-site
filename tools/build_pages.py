def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for rel, fn in PAGES.items():
        path = SITE / rel
        new = fn()
        old = path.read_text(encoding="utf-8") if path.exists() else None
        # seo_inject.py adds its block after this generator runs, so compare
        # with that block stripped.
        if old is not None:
            import re
            old_cmp = re.sub(r"\n<!-- SEO:VASL -->.*?<!-- /SEO:VASL -->", "", old, flags=re.S)
        else:
            old_cmp = None
        if old_cmp != new:
            stale.append(rel)
            if not check:
                path.write_text(new, encoding="utf-8")
    if check:
        if stale:
            print("out of date:", ", ".join(stale))
            return 1
        print("pages are current")
        return 0
    print(f"wrote {len(stale)} page(s)")
    return 0


